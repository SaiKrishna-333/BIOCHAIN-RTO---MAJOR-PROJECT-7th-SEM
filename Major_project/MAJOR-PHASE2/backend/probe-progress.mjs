import "dotenv/config";
import mongoose from "mongoose";
await mongoose.connect(process.env.MONGO_URI || "mongodb://localhost:27017/BioChainRTO");
const db = mongoose.connection.db;
const citizenA = await db.collection("users").countDocuments({ email: "ananya.demo@biochain.com" });
const vehicles = await db.collection("vehicles").find({ regNumber: { $in: ["KA45CF1234", "TN45CF1234", "KA45CF2468", "KA45CF1357", "KA45CF8642"] } }).toArray();
const requests = await db.collection("requests").countDocuments({});
const challans = await db.collection("challans").countDocuments({});
const service = await db.collection("servicerecords").countDocuments({});
const damage = await db.collection("damageevents").countDocuments({});
const battery = await db.collection("batterypassports").countDocuments({});
const theft = await db.collection("theftreports").countDocuments({});
const inherit = await db.collection("inheritancetransfers").countDocuments({});
const cases = await db.collection("investigationcases").countDocuments({});
const alerts = await db.collection("anomalyalerts").countDocuments({});
const conflicts = await db.collection("identityconflicts").countDocuments({});
console.log("progress probe:");
console.log("  citizenA:", citizenA);
console.log("  vehicles:", vehicles.map((v) => v.regNumber).join(", "));
console.log("  requests:", requests, "challans:", challans, "service:", service);
console.log("  damageEvents:", damage, "battery:", battery, "theft:", theft, "inheritance:", inherit);
console.log("  cases:", cases, "anomalyAlerts:", alerts, "identityConflicts:", conflicts);
await mongoose.disconnect();
